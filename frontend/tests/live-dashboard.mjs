// Real HTTP + Vue SSR integration, using a NEW disposable backend data directory.
// This verifies data flow and rendered content, not browser layout/click handling.
import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { createSSRApp } from 'vue'
import { renderToString } from '@vue/server-renderer'
import { useDashboard } from '../src/dashboard.js'

const base = process.env.DASHBOARD_URL || 'http://127.0.0.1:5173'
const request = (path, options) => fetch(base + path, options)
const ui = useDashboard(request)
await ui.reload()
assert.equal(ui.error.value, '')
assert.equal(ui.dashboard.value.initialized, false, 'Use a new disposable NOVEL_DATA_DIR; existing projects are never overwritten.')
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' })
async function render(name, props) {
  const { default: component } = await server.ssrLoadModule(`/src/components/${name}.vue`)
  return renderToString(createSSRApp(component, props))
}
function healthy() { assert.equal(ui.error.value, '', ui.error.value) }
try {
  await ui.initialize('旅人寻找归乡路，沿途收集路标石。'); healthy()
  const initial = JSON.parse(JSON.stringify(ui.dashboard.value.committed_state))
  let html = await render('StoryStatePanel', { world: initial })
  assert.match(html, /正式世界状态/); assert.match(html, /旅人/); assert.match(html, /起始村落/)
  html = await render('ChapterNavigator', { chapters: ui.dashboard.value.chapters, premise: initial.outline.premise, selected: 1 })
  assert.match(html, /not generated/); assert.match(html, /当前工作章/)
  console.log('PASS initialize: committed roles/world/outline and state_0')

  assert.equal(ui.canGenerate.value, false)
  html = await render('StoryDirections', { planning: ui.selectedPlanning.value, chapterNumber: 1, isWorking: true, canPlan: true })
  assert.match(html, /Generate Story Options/)
  await ui.generateOptions(); healthy()
  const options1 = JSON.parse(JSON.stringify(ui.dashboard.value.current_planning))
  assert.deepEqual(options1.branches.map(b => b.strategy).sort(), ['escalation', 'progression', 'revelation'])
  html = await render('StoryDirections', { planning: options1, chapterNumber: 1, isWorking: true, canPlan: true })
  for (const strategy of ['Progression', 'Escalation', 'Revelation']) assert.match(html, new RegExp(strategy))
  assert.equal((html.match(/class="branch-card"/g) || []).length, 3)
  const escalation = options1.branches.find(b => b.strategy === 'escalation')
  await ui.chooseBranch(escalation.id); healthy()
  assert.equal(ui.canGenerate.value, true)
  assert.deepEqual(ui.dashboard.value.committed_state, initial)
  console.log('PASS three distinct options -> human escalation selection persisted; world unchanged')

  await ui.generate(); healthy()
  assert.match(ui.record.value.text, /落石封住退路/)
  assert.equal(ui.canPlan.value, false)
  assert.deepEqual(ui.dashboard.value.committed_state, initial)
  assert.equal(ui.canApprove.value, true)
  html = await render('ChapterWorkspace', { chapter: ui.selectedChapter.value, record: ui.record.value, canApprove: true })
  assert.match(html, /未提交草稿/); assert.match(html, /PASS · 机审通过/); assert.match(html, /路标石/)
  console.log('PASS generate chapter 1: draft + review; committed world unchanged')

  await ui.approve(); healthy()
  assert.equal(ui.selectedPlanning.value.status, 'approved')
  assert.equal(ui.selectedPlanning.value.selected_branch_id, escalation.id)
  assert.deepEqual(ui.selectedPlanning.value.branches, options1.branches)
  assert.equal(ui.dashboard.value.committed_state.inventory[0].quantity, 1)
  assert.equal(ui.dashboard.value.snapshots.length, 2)
  html = await render('StateChanges', { log: ui.dashboard.value.recent_state_changes })
  assert.match(html, /数量/); assert.match(html, /新增记录/); assert.match(html, /第 1 章已提交/)
  html = await render('ChapterWorkspace', { chapter: ui.selectedChapter.value, record: ui.record.value })
  assert.match(html, /正式正文/); assert.doesNotMatch(html, /未提交草稿/)
  html = await render('SnapshotHistory', { snapshots: ui.dashboard.value.snapshots })
  assert.match(html, /state_1/); assert.match(html, /创建时间/)
  console.log('PASS approve chapter 1: official text, mutations and state_1 rendered')

  await ui.select(3); healthy()
  assert.equal(ui.record.value, null)
  html = await render('ChapterWorkspace', { chapter: ui.selectedChapter.value, record: null })
  assert.match(html, /本章尚未生成/)
  await ui.generateOptions(); healthy()
  const oldOptions2 = ui.dashboard.value.current_planning.id
  await ui.chooseBranch(ui.dashboard.value.current_planning.branches[0].id); healthy()
  await ui.generateOptions(); healthy()
  assert.notEqual(ui.dashboard.value.current_planning.id, oldOptions2)
  assert.equal(ui.dashboard.value.current_planning.selected_branch_id, null)
  const options2 = JSON.parse(JSON.stringify(ui.dashboard.value.current_planning))
  await ui.chooseBranch(options2.branches.find(b => b.strategy === 'progression').id); healthy()
  await ui.generate(); healthy()
  assert.equal(ui.record.value.chapter_number, 2)
  assert.deepEqual(ui.dashboard.value.chapters.slice(0, 3).map(c => c.status), ['approved', 'draft', 'not_generated'])
  const revelation = options2.branches.find(b => b.strategy === 'revelation')
  const blocked = await request('/api/chapter/branches/select', { method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ planning_id: options2.id, branch_id: revelation.id }) })
  assert.equal(blocked.status, 409)
  const lockedId = ui.dashboard.value.current_planning.selected_branch_id
  await ui.chooseBranch(revelation.id)
  assert.equal(ui.dashboard.value.current_planning.selected_branch_id, lockedId)
  html = await render('StoryDirections', { planning: options2, chapterNumber: 2, isWorking: true, canPlan: false, draft: ui.record.value })
  assert.match(html, /Discard Draft/)
  assert.match(html, /disabled[^>]*>Choose revelation/)
  await ui.discardDraft(); healthy()
  assert.equal(ui.record.value, null)
  await ui.chooseBranch(revelation.id); healthy()
  await ui.generate(); healthy()
  assert.match(ui.record.value.text, /发现暗纹指向故乡/)
  console.log('PASS chapter 2 options regenerated; draft locks selection; discard unlocks; revelation draft generated')
  await ui.rollback(1); healthy()
  assert.equal(ui.dashboard.value.current_planning.status, 'none')
  assert.equal(ui.dashboard.value.current_planning.chapter_number, 2)
  assert.equal(ui.selectedPlanning.value.status, 'approved')
  assert.equal(ui.record.value.status, 'approved')
  await ui.rollback(0); healthy()
  assert.deepEqual(ui.dashboard.value.committed_state, initial)
  assert.equal(ui.record.value, null)
  assert.equal(ui.dashboard.value.recent_state_changes, null)
  assert.equal(ui.dashboard.value.snapshots.length, 1)
  assert.equal(ui.dashboard.value.current_planning.status, 'none')
  assert(ui.dashboard.value.chapters.every(c => c.status === 'not_generated'))
  html = await render('StateChanges', { log: null })
  assert.match(html, /尚无章节提交/)
  console.log('PASS chapter 2 draft -> rollback state_0: all Dashboard sections refreshed')

  const firstProject = ui.projectId.value
  await ui.generateOptions(); healthy()
  await ui.chooseBranch(ui.selectedPlanning.value.branches[0].id); healthy()
  await ui.generate(); healthy()
  const savedDraft = JSON.parse(JSON.stringify(ui.record.value))
  const savedPlan = JSON.parse(JSON.stringify(ui.selectedPlanning.value))
  await ui.initialize('第二个独立故事', '项目隔离验收'); healthy()
  const secondProject = ui.projectId.value
  assert.notEqual(firstProject, secondProject)
  assert.equal(ui.projects.value.length, 2)
  assert.equal(ui.record.value, null)
  assert.equal(ui.selectedPlanning.value.status, 'none')
  html = await render('ProjectLibrary', { projects: ui.projects.value, projectId: secondProject, busy: false })
  assert.match(html, /项目隔离验收/)
  assert.match(html, /加载项目/)
  assert.match(html, /新建项目/)
  await ui.loadProject(firstProject); healthy()
  assert.deepEqual(ui.record.value, savedDraft)
  assert.deepEqual(ui.selectedPlanning.value, savedPlan)
  await ui.approve(); healthy()
  await ui.loadProject(secondProject); healthy()
  assert.equal(ui.dashboard.value.committed_state.chapter_number, 0)
  assert.equal(ui.record.value, null)
  console.log('PASS project library: create isolated story, render history, reload saved draft/plan, approve without affecting another project')
} finally { await server.close() }
